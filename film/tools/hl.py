import re, json, sys, html
from xml.etree import ElementTree as ET
S = sys.argv[1]
def load(doc):
    txt = open(f'{S}/bbox/{doc}.html', encoding='utf-8').read()
    txt = re.sub(r'<!DOCTYPE[^>]*>', '', txt)
    txt = txt.replace('xmlns="http://www.w3.org/1999/xhtml"', '')
    root = ET.fromstring(txt)
    pages = []
    for p in root.iter('page'):
        W, H = float(p.get('width')), float(p.get('height'))
        words = []
        for w in p.iter('word'):
            words.append(dict(t=w.text or '', x0=float(w.get('xMin')), y0=float(w.get('yMin')), x1=float(w.get('xMax')), y1=float(w.get('yMax'))))
        pages.append(dict(W=W, H=H, words=words))
    return pages
DOCS = {d: load(d) for d in ['brev','svar','sok','v1','v2']}
def norm(s):
    return re.sub(r'\s+', '', s).replace(' ','')
def find(doc, page, phrase, occ=0, near=None):
    pg = DOCS[doc][page-1]
    words = pg['words']
    # build concatenated string
    cat = ''; owner = []
    for i, w in enumerate(words):
        t = norm(w['t']); cat += t; owner += [i]*len(t)
    target = norm(phrase)
    hits = [m.start() for m in re.finditer(re.escape(target), cat)]
    if not hits:
        raise SystemExit(f'NOT FOUND {doc} p{page}: {phrase}')
    if near is not None:
        hits.sort(key=lambda h: abs(words[owner[h]]['y0']/pg['H'] - near))
        h = hits[0]
    else:
        h = hits[occ]
    idx = sorted(set(owner[h:h+len(target)]))
    # group into lines by y
    lines = []
    for i in idx:
        w = words[i]
        for L in lines:
            if abs(L['y0'] - w['y0']) < 3 and w['x0'] - L['x1'] < 40:
                L['x0'] = min(L['x0'], w['x0']); L['x1'] = max(L['x1'], w['x1']); L['y1'] = max(L['y1'], w['y1']); break
        else:
            lines.append(dict(w))
    W, H = pg['W'], pg['H']
    rects = [[round(L['x0']/W,5), round(L['y0']/H,5), round((L['x1']-L['x0'])/W,5), round((L['y1']-L['y0'])/H,5)] for L in lines]
    return dict(doc=doc, page=page, rects=rects, aspect=round(H/W,5))
specs = json.load(open(sys.argv[2]))
out = {}
for sid, sp in specs.items():
    out[sid] = find(sp['doc'], sp['page'], sp['phrase'], sp.get('occ', 0), sp.get('near'))
json.dump(out, open(sys.argv[3], 'w'), indent=1, ensure_ascii=False)
print(len(out), 'highlights')
# also emit a JS data file for the film
if len(sys.argv) > 4:
    with open(sys.argv[4], 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/hl.py from the original PDFs - word positions (normalised to page size)\n')
        f.write('window.HL = ' + json.dumps(out, ensure_ascii=False) + ';\n')
