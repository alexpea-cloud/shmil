"""Prepares map data for the map demo from Kartverket municipality borders
(robhop/fylker-og-kommuner, CC BY 4.0, based on Kartverket data).
Projects to UTM zone 33 (km), simplifies, writes demos/geo.js.
Usage: python3 tools/geo_prepare.py <Kommuner-L.geojson> <Norge-L.geojson> <out.js>
"""
import json, math, sys

OWN = {'1812', '1813', '1815', '1816', '1818', '1820', '1822', '1824', '1825', '1826', '1827'}

def tm(lon, lat, lon0=15.0, k0=0.9996):
    a, f = 6378137.0, 1 / 298.257222101
    e2 = f * (2 - f); ep2 = e2 / (1 - e2)
    phi, lam = math.radians(lat), math.radians(lon - lon0)
    N = a / math.sqrt(1 - e2 * math.sin(phi) ** 2)
    T = math.tan(phi) ** 2; C = ep2 * math.cos(phi) ** 2; A = math.cos(phi) * lam
    M = a * ((1 - e2 / 4 - 3 * e2 ** 2 / 64 - 5 * e2 ** 3 / 256) * phi - (3 * e2 / 8 + 3 * e2 ** 2 / 32 + 45 * e2 ** 3 / 1024) * math.sin(2 * phi)
             + (15 * e2 ** 2 / 256 + 45 * e2 ** 3 / 1024) * math.sin(4 * phi) - (35 * e2 ** 3 / 3072) * math.sin(6 * phi))
    x = k0 * N * (A + (1 - T + C) * A ** 3 / 6 + (5 - 18 * T + T ** 2 + 72 * C - 58 * ep2) * A ** 5 / 120)
    y = k0 * (M + N * math.tan(phi) * (A ** 2 / 2 + (5 - T + 9 * C + 4 * C ** 2) * A ** 4 / 24 + (61 - 58 * T + T ** 2 + 600 * C - 330 * ep2) * A ** 6 / 720))
    return x / 1000.0, y / 1000.0

def dp(pts, tol):
    if len(pts) < 4: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        i, j = stack.pop()
        ax, ay = pts[i]; bx, by = pts[j]; dx, dy = bx - ax, by - ay; L = math.hypot(dx, dy) or 1e-9
        best, bi = -1, -1
        for k in range(i + 1, j):
            px, py = pts[k]
            d = abs(dy * px - dx * py + bx * ay - by * ax) / L if L > 1e-6 else math.hypot(px - ax, py - ay)  # closed ring: distance to start
            if d > best: best, bi = d, k
        if best > tol: keep[bi] = True; stack += [(i, bi), (bi, j)]
    return [p for p, k in zip(pts, keep) if k]

def area(r):
    return 0.5 * sum(r[i][0] * r[i - 1][1] - r[i - 1][0] * r[i][1] for i in range(len(r)))

def rings(geom):
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    for poly in polys:
        for k, ring in enumerate(poly):
            yield k, ring

def project(geom, tol, minarea):
    out, tot = [], 0.0
    for k, ring in rings(geom):
        p = [tm(lon, lat) for lon, lat in ring]
        A = area(p)
        tot += A if k == 0 else -abs(A)
        if abs(A) < minarea: continue
        s = dp(p, tol)
        if len(s) >= 4: out.append([[round(x, 2), round(-y, 2)] for x, y in s])
    return out, abs(tot)

kom = json.load(open(sys.argv[1], encoding='utf-8'))
own, ctx, total = [], [], 0.0
for f in kom['features']:
    nr = f['properties']['kommunenummer']; name = f['properties']['kommunenavn']
    if nr in OWN:
        paths, A = project(f['geometry'], 0.06, 0.02)
        total += A
        own.append({'nr': nr, 'name': name.replace('Aarborte - ', ''), 'area': round(A, 1), 'paths': paths})
    else:
        g = f['geometry']['coordinates']
        lon, lat = g[0][0] if f['geometry']['type'] == 'Polygon' else g[0][0][0]
        if 9.5 < lon < 17.0 and 64.0 < lat < 67.6:
            paths, _ = project(f['geometry'], 0.15, 0.2)
            ctx.append({'nr': nr, 'name': f['properties']['kommunenavn'], 'paths': paths})
nor = json.load(open(sys.argv[2], encoding='utf-8'))
norway = []
for f in nor['features']:
    p, _ = project(f['geometry'], 1.2, 15)
    norway += p
towns = {name: [round(v, 2) for v in tm(lon, lat)] for name, lon, lat in
         [('Brønnøysund', 12.2117, 65.4747), ('Sandnessjøen', 12.6316, 66.0217), ('Mosjøen', 13.1913, 65.8370)]}
towns = {k: [v[0], -v[1]] for k, v in towns.items()}
with open(sys.argv[3], 'w', encoding='utf-8') as fo:
    fo.write('// Generated by tools/geo_prepare.py – kommunegrenser fra Kartverket (CC BY 4.0) via robhop/fylker-og-kommuner.\n')
    fo.write('// Koordinater: UTM sone 33, km (y nedover).\n')
    fo.write('window.GEO = ' + json.dumps({'own': own, 'ctx': ctx, 'norway': norway, 'towns': towns}, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('own', len(own), 'total area km2', round(total, 1), 'ctx', len(ctx), 'norway rings', len(norway))
for o in own: print(o['name'], o['area'], len(o['paths']))
